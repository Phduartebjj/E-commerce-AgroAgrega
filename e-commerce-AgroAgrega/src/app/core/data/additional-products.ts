function createProduct(
  id: number,
  category: ProductCategory,
  title: string,
  price: number,
  description: string,
  rating: number,
  brand: BrandOption,
  weeklySales: number,
  imageIndex = 0,
): ProductModel {
  const images = categoryImages[category];

  return {
    id: `agro-${id.toString().padStart(3, '0')}`,
    category,
    title,
    price,
    description,
    images: [images[imageIndex % images.length]],
    rating,
    brand,
    weeklySales,
  };
}

